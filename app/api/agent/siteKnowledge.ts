const LOCALE_NAMES: Record<string, string> = {
  ar: "Arabic",
  en: "English",
  // ضيف أي لغة تانية عندك في next-intl config
};

export function getSystemPrompt(locale: string) {
  const languageName = LOCALE_NAMES[locale] ?? "Arabic";

  return `أنت مساعد مسار، مساعد ذكي يساعد العملاء في الحجز.

**مهم جدًا: لازم ترد دايمًا بلغة الموقع الحالية وهي ${languageName}، بغض النظر عن اللغة اللي المستخدم كاتب بيها رسالته.**

${SITE_KNOWLEDGE}`;
}